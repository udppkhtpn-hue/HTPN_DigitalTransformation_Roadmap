/**
 * The spoken script, from the markdown it is written in to the data the
 * presenter view reads.
 *
 *   node scripts/make-script.mjs
 *
 * Reads "Built From Within — 20-minute keynote script.md" and writes
 * src/content/script.ts. The markdown stays the place the script is edited;
 * this keeps the deck in step with it, and refuses to write anything the deck
 * cannot honour: a sheet whose title, press count or planned time disagrees
 * with scenes.ts, or a sheet with no script at all.
 *
 * Shape the parser expects:
 *   ## Act 1 · Title (S-01 to S-04, about 3:23)   starts an act; a plain
 *                                                  line after it is its note
 *   ### S-02 Three forces  (69s, 163 words)       starts a sheet;
 *                                                  "(46s + about 30s of reel, ...)"
 *                                                  counts the reel in the time
 *   *\[Press 2: what the press brings up\]*        starts press 2; text before
 *                                                  any press line is press 1
 *   ## Timing and checks                          ends the script
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { SCENES } from '../src/content/scenes.ts'

const SRC = 'Built From Within — 20-minute keynote script.md'
const OUT = 'src/content/script.ts'

const lines = readFileSync(SRC, 'utf8').split('\n')
const end = lines.findIndex((l) => l.startsWith('## Timing and checks'))
const body = end < 0 ? lines : lines.slice(0, end)

const clean = (t) => t.replace(/\\([[\]])/g, '$1').replace(/^\*|\*$/g, '').trim()
const words = (t) => t.trim().split(/\s+/).filter(Boolean).length

const sheets = []
let act = null
let pendingAct = null
let sheet = null
let block = null

const flushPara = (buf) => {
  const t = buf.join(' ').trim()
  buf.length = 0
  if (t && block) block.paras.push(t)
}

let buf = []
for (const raw of body) {
  const line = raw.trimEnd()

  const a = /^## (Act \d+ · .+?|Close)\s*(?:\((.*)\))?\s*$/.exec(line)
  if (a) {
    flushPara(buf)
    pendingAct = { title: a[1].replace(/\s*\(.*$/, ''), note: '' }
    sheet = null
    block = null
    continue
  }
  if (line.startsWith('## ')) {
    flushPara(buf)
    pendingAct = null
    sheet = null
    block = null
    continue
  }

  const h = /^### (S-\d+) (.+?)\s+\((\d+)s(?: \+ about (\d+)s of reel)?, (\d+) words\)\s*$/.exec(line)
  if (h) {
    flushPara(buf)
    sheet = {
      sheet: h[1],
      title: h[2],
      seconds: Number(h[3]) + Number(h[4] ?? 0),
      reel: Number(h[4] ?? 0),
      act: pendingAct,
      blocks: [],
    }
    pendingAct = null
    sheets.push(sheet)
    block = null
    continue
  }

  if (!sheet) {
    // A plain line straight after an act heading is that act's note.
    if (pendingAct && line.trim()) pendingAct.note = line.trim()
    continue
  }

  const p = /^\*\\\[Press (\d+): (.*)\\\]\*$/.exec(line)
  if (p) {
    flushPara(buf)
    block = { press: Number(p[1]), cue: clean(p[2]), paras: [] }
    sheet.blocks.push(block)
    continue
  }

  if (!line.trim()) {
    flushPara(buf)
    continue
  }
  if (!block) throw new Error(`${sheet.sheet}: text before the first press line: "${line.slice(0, 40)}"`)
  buf.push(line.trim())
}
flushPara(buf)

// ── checks against the deck ────────────────────────────────────────────────
const problems = []
for (const s of SCENES) {
  const t = sheets.find((x) => x.sheet === s.sheet)
  if (!t) {
    problems.push(`${s.sheet} ${s.title}: no script`)
    continue
  }
  if (t.title !== s.title) problems.push(`${s.sheet}: script calls it "${t.title}", deck calls it "${s.title}"`)
  if (t.blocks.length !== s.steps) problems.push(`${s.sheet}: ${t.blocks.length} presses in the script, ${s.steps} in the deck`)
  t.blocks.forEach((b, i) => {
    if (b.press !== i + 1) problems.push(`${s.sheet}: press ${b.press} out of order`)
    if (!b.paras.length) problems.push(`${s.sheet} press ${b.press}: nothing to say`)
  })
  if (t.seconds !== s.seconds) problems.push(`${s.sheet}: script runs ${t.seconds}s, deck plans ${s.seconds}s`)
}
for (const t of sheets) if (!SCENES.some((s) => s.sheet === t.sheet)) problems.push(`${t.sheet}: in the script, not in the deck`)
if (problems.length) {
  console.error(problems.map((p) => '  ' + p).join('\n'))
  process.exit(1)
}

// ── write ──────────────────────────────────────────────────────────────────
const q = (v) => JSON.stringify(v)
const out = [
  '// Generated by scripts/make-script.mjs from the keynote script. Do not edit by hand.',
  '',
  'export interface ScriptBlock {',
  '  /** Zero-based click this text belongs to. */',
  '  step: number',
  '  /** What the click brings up, for the speaker. */',
  '  cue: string',
  '  paras: string[]',
  '}',
  '',
  'export interface SheetScript {',
  '  sheet: string',
  '  title: string',
  '  /** Spoken seconds, plus any reel that plays on its own. */',
  '  seconds: number',
  '  /** Of which the sheet runs on its own, unspoken. */',
  '  reel: number',
  '  words: number',
  '  /** Set on the first sheet of an act. */',
  '  act?: { title: string; note: string }',
  '  blocks: ScriptBlock[]',
  '}',
  '',
  'export const SCRIPT: Record<string, SheetScript> = {',
]
let total = 0
for (const s of sheets) {
  const w = s.blocks.reduce((n, b) => n + b.paras.reduce((m, p) => m + words(p), 0), 0)
  total += w
  out.push(`  ${q(s.sheet)}: {`)
  out.push(`    sheet: ${q(s.sheet)},`, `    title: ${q(s.title)},`, `    seconds: ${s.seconds},`, `    reel: ${s.reel},`, `    words: ${w},`)
  if (s.act) out.push(`    act: { title: ${q(s.act.title)}, note: ${q(s.act.note)} },`)
  out.push('    blocks: [')
  for (const b of s.blocks) {
    out.push(`      { step: ${b.press - 1}, cue: ${q(b.cue)}, paras: [`)
    for (const p of b.paras) out.push(`        ${q(p)},`)
    out.push('      ] },')
  }
  out.push('    ],', '  },')
}
out.push('}', '')
writeFileSync(OUT, out.join('\n'))
console.log(`${OUT}: ${sheets.length} sheets, ${sheets.reduce((n, s) => n + s.blocks.length, 0)} presses, ${total} words`)
