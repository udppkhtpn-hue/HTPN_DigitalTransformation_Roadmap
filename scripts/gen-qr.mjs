/**
 * QR codes, generated at build time into path data.
 *
 * Building the path ourselves rather than taking the library's SVG keeps the
 * runtime dependency out of the bundle entirely and lets the codes inherit
 * --chalk like everything else on the sheet.
 */
import { writeFileSync } from 'node:fs'
import QRCode from 'qrcode'

const URLS = {
  showcase: 'https://htpn-showcase-v2.vercel.app/',
  innovathon: 'https://udppkhtpn-hue.github.io/innovathon2026/',
  padlet: 'https://padlet.com/drsyafiz/bengkel-produktiviti-digital-ai-untuk-transformasi-perkhidma-s024ha3em14j8gw35eyo',
}

/** One rect per dark module, merged into a single path. */
function toPath(url) {
  const qr = QRCode.create(url, { errorCorrectionLevel: 'M' })
  const n = qr.modules.size
  const data = qr.modules.data
  let d = ''
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      if (data[y * n + x]) d += `M${x} ${y}h1v1h-1z`
    }
  }
  return { size: n, d }
}

const out = Object.entries(URLS).map(([key, url]) => {
  const { size, d } = toPath(url)
  console.log(`${key.padEnd(12)} ${size}×${size} modules  ${d.length} chars`)
  return { key, url, size, d }
})

writeFileSync(
  'src/content/qr.ts',
  `// Generated by scripts/gen-qr.mjs — do not edit by hand.\n` +
    `export interface QrCode {\n  key: string\n  url: string\n  size: number\n  d: string\n}\n\n` +
    `export const QR: Record<string, QrCode> = {\n` +
    out
      .map(
        (o) =>
          `  ${o.key}: {\n    key: ${JSON.stringify(o.key)},\n    url: ${JSON.stringify(o.url)},\n    size: ${o.size},\n    d: ${JSON.stringify(o.d)},\n  },`,
      )
      .join('\n') +
    `\n}\n`,
)
console.log('src/content/qr.ts written')
